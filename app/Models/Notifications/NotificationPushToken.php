<?php

namespace App\Models\Notifications;

use Illuminate\Database\Eloquent\Model;

class NotificationPushToken extends Model
{
    protected $fillable = [
        'user_id',
        'token',
        'platform',
        'last_used_at',
    ];

    protected function casts(): array
    {
        return [
            'last_used_at' => 'datetime',
        ];
    }
}
